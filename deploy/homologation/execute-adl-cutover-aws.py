def inspect_worker_failure(consumers):
    report={'records':[],'signals':[],'rawLogPrinted':False};raw=b''
    for c in consumers:
        require(re.fullmatch('[0-9a-f]{12,64}',c['id']) is not None,'WORKER_CONTAINER_ID_UNVERIFIED')
        logs=subprocess.run(['docker','logs','--tail','80',c['id']],capture_output=True,timeout=15,check=False)
        require(logs.returncode==0,'WORKER_PRIVATE_LOG_READ_FAILED')
        data=logs.stdout+b'\n'+logs.stderr;raw+=data
        report['signals']=sorted(set(report['signals']+classify(data)))
        for line in data.decode(errors='replace').splitlines():
            try:entry=json.loads(line)
            except Exception:continue
            if not isinstance(entry,dict) or entry.get('operation') not in ('homologation.admission','homologation.preflight'):continue
            reason=entry.get('reason')
            if reason not in ('capacity_not_reviewed','mac_shutdown_not_confirmed','supplier_cooldown_not_confirmed','supplier_cooldown_pending','memory_budget_exceeded'):continue
            row={'operation':entry['operation'],'reason':reason,'status':'blocked'}
            if isinstance(entry.get('lanes'),list):
                allowed=('allowed','responseLimitBytes','memoryBudgetBytes','availableMemoryBytes','heapHeadroomBytes','memoryHeadroomBytes')
                row['lanes']=[{k:v for k,v in item.items() if k in allowed and type(v) in (bool,int,float) and (type(v) is bool or math.isfinite(v))} for item in entry['lanes'] if isinstance(item,dict)]
            report['records'].append(row)
    report['records']=report['records'][-8:];report['privateLogSha256']=hashlib.sha256(raw).hexdigest()
    return report,raw

